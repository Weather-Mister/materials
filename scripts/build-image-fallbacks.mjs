import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const sourceFiles = [
  "public/course.js",
  "public/course-weeks-3-4.js",
  "public/source-overhaul.js",
];
const outputPath = path.join(ROOT, "public/image-fallbacks.js");
const refs = new Set();
const imageRe = /src=['"]\.\/assets\/([^?'"]+\.(?:webp|png|jpe?g|svg))(?:\?[^'"]*)?['"]/gi;

for (const rel of sourceFiles) {
  const text = fs.readFileSync(path.join(ROOT, rel), "utf8");
  let match;
  while ((match = imageRe.exec(text))) refs.add(match[1]);
}

if (!refs.size) throw new Error("No learner-facing image references found.");

const mimeFor = (name) => {
  const ext = path.extname(name).toLowerCase();
  if (ext === ".webp") return "image/webp";
  if (ext === ".png") return "image/png";
  if (ext === ".jpg" || ext === ".jpeg") return "image/jpeg";
  if (ext === ".svg") return "image/svg+xml";
  throw new Error(`Unsupported image type: ${name}`);
};

const payload = {};
for (const name of [...refs].sort()) {
  const assetPath = path.join(ROOT, "public/assets", name);
  if (!fs.existsSync(assetPath)) throw new Error(`Missing learner-facing image asset: ${assetPath}`);
  const data = fs.readFileSync(assetPath);
  if (name.endsWith(".webp")) {
    if (data.length < 12 || data.subarray(0, 4).toString("ascii") !== "RIFF" || data.subarray(8, 12).toString("ascii") !== "WEBP") {
      throw new Error(`Invalid WebP asset: ${assetPath}`);
    }
  }
  payload[name] = `data:${mimeFor(name)};base64,${data.toString("base64")}`;
}

const body =
  "/* Generated by scripts/build-image-fallbacks.mjs. " +
  "Normal asset URLs remain primary; these data URIs are used only after an image load failure. */\n" +
  `window.MATERIALS_IMAGE_FALLBACKS = Object.freeze(${JSON.stringify(payload)});\n`;

fs.writeFileSync(outputPath, body);
console.log(`Image fallback registry: ${refs.size} assets, ${Buffer.byteLength(body)} bytes`);
